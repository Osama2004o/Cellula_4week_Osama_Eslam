from typing import Any, Optional
from pydantic import BaseModel, Field


class TextToSQLRequest(BaseModel):
    text: str = Field(
        ...,
        description="Natural language request or transcribed text to convert into a SQLite query",
        example="Show me the total sales by product category."
    )
    schema_context: Optional[str] = Field(
        default=None,
        description="Optional database schema definition (DDL/CREATE TABLE or table descriptions) to ground the SQLite query generation",
        example="CREATE TABLE sales (id INTEGER PRIMARY KEY, product_category TEXT, amount REAL, sale_date TEXT);"
    )


class TextToSQLResponse(BaseModel):
    query: str = Field(..., description="Original user request/transcription")
    sql: str = Field(..., description="Clean, executable SQLite query generated by LLM")
    dialect: str = Field(default="SQLite", description="Target database engine (always SQLite)")
    model_used: str = Field(..., description="OpenRouter model identifier used for generation")


class ExecuteSQLRequest(BaseModel):
    sql: str = Field(
        ...,
        description="SQLite query to execute against the active SQLite database",
        example="SELECT name, price, stock_quantity FROM products ORDER BY price DESC LIMIT 5;"
    )


class ExecuteSQLResponse(BaseModel):
    success: bool = Field(..., description="Whether the query executed successfully")
    query: str = Field(..., description="The executed SQL query string")
    columns: list[str] = Field(default_factory=list, description="Column names returned by the query")
    rows: list[list[Any]] = Field(default_factory=list, description="Row values as 2D list")
    row_count: int = Field(default=0, description="Total number of rows returned or affected")
    execution_time_ms: float = Field(default=0.0, description="Query execution time in milliseconds")
    error: Optional[str] = Field(default=None, description="Detailed error message if execution failed")
